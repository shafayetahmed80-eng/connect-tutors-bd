import { mkdirSync, writeFileSync } from "node:fs";
const CSS_URL = "https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,500;9..40,600;9..40,700;9..40,800&family=Manrope:wght@400;500;600;700;800&family=Noto+Sans+Bengali:wght@400;500;600;700&display=swap";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";
// Only the character sets this site actually serves: English plus Bengali.
const KEEP = new Set(["latin", "latin-ext", "bengali"]);
const OUT_DIR = "client/public/fonts";

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();
mkdirSync(OUT_DIR, { recursive: true });

// Google emits "/* subset */" immediately before each @font-face block.
const blocks = css.split(/\/\* (?=[a-z-]+ \*\/)/).slice(1);
const kept = [];
let bytes = 0;

for (const raw of blocks) {
  const subset = raw.slice(0, raw.indexOf(" */")).trim();
  if (!KEEP.has(subset)) continue;
  const body = raw.slice(raw.indexOf("*/") + 2).trim();
  const family = body.match(/font-family: '([^']+)'/)[1];
  const weight = body.match(/font-weight: ([^;]+);/)[1].trim().replace(/\s+/g, "-");
  const url = body.match(/url\((https:[^)]+)\)/)[1];
  const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${weight}-${subset}.woff2`;
  const data = Buffer.from(await (await fetch(url, { headers: { "User-Agent": UA } })).arrayBuffer());
  writeFileSync(`${OUT_DIR}/${file}`, data);
  bytes += data.length;
  kept.push(body.replace(url, `/fonts/${file}`));
}

const header = [
  "/* Self-hosted Google Fonts - generated by scripts/fetch-google-fonts.mjs.",
  " * Do not hand-edit; re-run the script to refresh.",
  ` * Subsets kept: ${[...KEEP].join(", ")}. Serving these locally means the site`,
  " * renders identically offline and never calls fonts.gstatic.com. */",
  "",
].join("\n");

writeFileSync("client/src/fonts.css", header + kept.join("\n\n") + "\n");
console.log(`kept ${kept.length}/${blocks.length} faces, ${(bytes / 1024).toFixed(0)} KB`);
