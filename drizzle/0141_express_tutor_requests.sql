CREATE TABLE IF NOT EXISTS `express_tutor_requests` (
  `id` int AUTO_INCREMENT NOT NULL PRIMARY KEY,
  `phone` varchar(16) NOT NULL,
  `guardianName` varchar(120),
  `classCourse` varchar(120) NOT NULL,
  `curriculumType` varchar(60),
  `subjects` varchar(255),
  `tuitionType` varchar(32) NOT NULL DEFAULT 'home',
  `cityLocationId` varchar(80),
  `locationId` varchar(80),
  `locationLabel` varchar(160) NOT NULL,
  `notes` varchar(500),
  `source` enum('home_hero','job_board','mobile_drawer','floating_action','direct') NOT NULL DEFAULT 'home_hero',
  `status` enum('new','contacted','converted','cancelled') NOT NULL DEFAULT 'new',
  `contactedAt` timestamp NULL,
  `contactedByAdminId` int,
  `convertedRequestId` int,
  `ipAddress` varchar(45),
  `userAgent` varchar(255),
  `createdAt` timestamp NOT NULL DEFAULT (now()),
  `updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `etr_city_fk` FOREIGN KEY (`cityLocationId`) REFERENCES `locations`(`id`),
  CONSTRAINT `etr_loc_fk` FOREIGN KEY (`locationId`) REFERENCES `locations`(`id`),
  CONSTRAINT `etr_admin_fk` FOREIGN KEY (`contactedByAdminId`) REFERENCES `users`(`id`),
  CONSTRAINT `etr_request_fk` FOREIGN KEY (`convertedRequestId`) REFERENCES `tutor_requests`(`id`),
  INDEX `express_tutor_requests_status_idx` (`status`),
  INDEX `express_tutor_requests_phone_idx` (`phone`),
  INDEX `express_tutor_requests_created_idx` (`createdAt`)
);
